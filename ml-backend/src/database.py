# src/database.py

import os
import sqlite3
import json
from datetime import datetime
from contextlib import contextmanager, closing


POSTGRES_URL = os.environ.get("DATABASE_URL", "").strip()
TABLE = "ml_alerts" if POSTGRES_URL else "alerts"
PARAM = "%s" if POSTGRES_URL else "?"


BASE_DIR = os.path.dirname(
    os.path.dirname(os.path.abspath(__file__))
)

DATABASE_DIR = os.environ.get(
    "CYBERVAULT_DATABASE_DIR", os.path.join(BASE_DIR, "database")
)
DATABASE_PATH = os.path.join(
    DATABASE_DIR,
    "cybervault.db"
)


@contextmanager
def get_connection():
    if POSTGRES_URL:
        import psycopg
        from psycopg.rows import dict_row

        with psycopg.connect(POSTGRES_URL, row_factory=dict_row) as connection:
            yield connection
        return

    os.makedirs(DATABASE_DIR, exist_ok=True)

    connection = sqlite3.connect(DATABASE_PATH)

    connection.row_factory = sqlite3.Row

    with closing(connection), connection:
        yield connection


def initialize_database():

    with get_connection() as connection:
        cursor = connection.cursor()

        identity = "INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY" if POSTGRES_URL else "INTEGER PRIMARY KEY AUTOINCREMENT"
        cursor.execute(f"""
            CREATE TABLE IF NOT EXISTS {TABLE} (

                id {identity},

                timestamp TEXT NOT NULL,

                threat TEXT NOT NULL,

                attack_type TEXT,

                confidence DOUBLE PRECISION,

                binary_confidence DOUBLE PRECISION,

                risk_score INTEGER,

                severity TEXT,

                recommended_actions TEXT,

                status TEXT DEFAULT 'NEW'
            )
        """)



def save_alert(alert):

    with get_connection() as connection:
        cursor = connection.cursor()

        timestamp = datetime.now().isoformat()

        cursor.execute(f"""
            INSERT INTO {TABLE} (
                timestamp,
                threat,
                attack_type,
                confidence,
                binary_confidence,
                risk_score,
                severity,
                recommended_actions,
                status
            )
            VALUES ({', '.join([PARAM] * 9)})
            RETURNING id
        """, (
            timestamp,
            alert.get("threat"),
            alert.get("attack_type"),
            alert.get("confidence"),
            alert.get("binary_confidence"),
            alert.get("risk_score"),
            alert.get("severity"),
            json.dumps(alert.get("recommended_actions", [])),
            "NEW"
        ))

        alert_id = cursor.fetchone()["id"]


        return alert_id


def get_alerts():

    with get_connection() as connection:
        cursor = connection.cursor()

        cursor.execute(f"""
            SELECT *
            FROM {TABLE}
            ORDER BY id DESC
        """)

        rows = cursor.fetchall()


        alerts = []

        for row in rows:

            alert = dict(row)

            alert["recommended_actions"] = json.loads(
                alert["recommended_actions"]
            )

            alerts.append(alert)

        return alerts


def get_alert(alert_id):

    with get_connection() as connection:
        cursor = connection.cursor()

        cursor.execute(f"""
            SELECT *
            FROM {TABLE}
            WHERE id = {PARAM}
        """, (alert_id,))

        row = cursor.fetchone()


        if row is None:
            return None

        alert = dict(row)

        alert["recommended_actions"] = json.loads(
            alert["recommended_actions"]
        )

        return alert


def update_alert_status(alert_id, status):

    with get_connection() as connection:
        cursor = connection.cursor()

        cursor.execute(f"""
            UPDATE {TABLE}
            SET status = {PARAM}
            WHERE id = {PARAM}
        """, (status, alert_id))


        updated = cursor.rowcount > 0


        return updated


if __name__ == "__main__":

    initialize_database()

    print("CyberVault database initialized.")
    print("Database: Postgres" if POSTGRES_URL else f"Database: {DATABASE_PATH}")