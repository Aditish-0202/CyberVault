import { readFile, readdir, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

/**
 * Regenerates `src/embedded-schema.ts` from the drizzle migrations.
 *
 * The embedded PGlite database applies this SQL directly, so it works without
 * reading files at runtime (including from the bundled API server).
 *
 * Run after `drizzle-kit generate`:
 *   pnpm --filter @workspace/db run migrations:embed
 */
const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, "..");
const migrationsDir = path.join(root, "drizzle");

const files = (await readdir(migrationsDir))
  .filter((file) => file.endsWith(".sql"))
  .sort();

if (files.length === 0) {
  throw new Error(`No .sql migrations found in ${migrationsDir}`);
}

const parts = [];
for (const file of files) {
  parts.push(`-- ${file}\n${await readFile(path.join(migrationsDir, file), "utf8")}`);
}

const output = `// Generated by scripts/embed-migrations.mjs - do not edit by hand.
// Mirrors lib/db/drizzle/*.sql so the embedded PGlite database can be created
// without filesystem access (works in dev and in the bundled build).
export const EMBEDDED_SCHEMA_SQL = ${JSON.stringify(parts.join("\n\n"))};
`;

await writeFile(path.join(root, "src", "embedded-schema.ts"), output);

console.log(`embedded ${files.length} migration(s) into src/embedded-schema.ts`);
